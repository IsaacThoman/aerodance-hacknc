// Metaplex Core NFTs on devnet: winner trophies (paid by the treasury) and hype
// stickers (paid by the spectator who sends them).
import { create, fetchAsset, mplCore } from "@metaplex-foundation/mpl-core";
import { createSignerFromKeypair, keypairIdentity, publicKey, type Umi } from "@metaplex-foundation/umi";
import { createUmi } from "@metaplex-foundation/umi-bundle-defaults";
import bs58 from "bs58";
import { RPC_URL, loadTreasury, withTimeout } from "./solana.ts";

function umiFor(secret: Uint8Array): Umi {
  const u = createUmi(RPC_URL, "confirmed").use(mplCore());
  return u.use(keypairIdentity(u.eddsa.createKeypairFromSecretKey(secret)));
}

let treasuryUmi: Umi | undefined;
function getTreasuryUmi(): Umi {
  if (treasuryUmi) return treasuryUmi;
  const treasury = loadTreasury();
  if (!treasury) throw new Error("No treasury yet. Run `npm run treasury`.");
  return (treasuryUmi = umiFor(treasury.secretKey));
}

export type MintedAsset = { asset: string; signature: string | null };

// The asset key is generated by the caller and kept until the mint lands, so a retry
// (or a timeout that actually landed) finds the existing asset instead of minting twice.
export async function mintAsset(opts: {
  payerSecret?: number[]; // defaults to the treasury
  assetSecret: number[];
  owner: string;
  name: string;
  uri: string;
}): Promise<MintedAsset> {
  const u = opts.payerSecret ? umiFor(Uint8Array.from(opts.payerSecret)) : getTreasuryUmi();
  const asset = createSignerFromKeypair(u, u.eddsa.createKeypairFromSecretKey(Uint8Array.from(opts.assetSecret)));
  const address = asset.publicKey.toString();
  const exists = () => fetchAsset(u, asset.publicKey).then(() => true, () => false);
  if (await exists()) return { asset: address, signature: null };
  try {
    const res = await withTimeout(
      create(u, { asset, owner: publicKey(opts.owner), name: opts.name, uri: opts.uri }).sendAndConfirm(u),
      45_000,
      "mint",
    );
    return { asset: address, signature: bs58.encode(res.signature) };
  } catch (err) {
    if (await exists()) return { asset: address, signature: null };
    throw err;
  }
}

export const mintTrophy = (assetSecret: number[], owner: string, name: string, uri: string) =>
  mintAsset({ assetSecret, owner, name, uri });
